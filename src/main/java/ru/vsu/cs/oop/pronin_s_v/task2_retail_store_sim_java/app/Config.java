package ru.vsu.cs.oop.pronin_s_v.task2_retail_store_sim_java.app;

/**
 * Глобальные параметры симуляции.
 * <p>
 * Этот класс содержит все настройки, управляющие вероятностями событий,
 * количеством покупателей, логикой скидок и другими аспектами работы модели.
 * <br><br>
 * Config используется всеми подсистемами (SimEngine, Event'ами,
 * PriceService, PurchaseEvent) и обеспечивает единый источник параметров.
 */
public class Config {

    /** Количество дней симуляции по умолчанию (если не указать вручную). */
    public static final int SIM_DAYS_DEFAULT = 3;

    // ─────────────────────────────────────────────────────────────────────────────
    // Вероятности генерации событий
    // ─────────────────────────────────────────────────────────────────────────────

    /** Вероятность создания события поставки товаров на склад. */
    public static final double P_DELIVERY = 0.6;

    /** Вероятность создания события выкладки товара в торговый зал. */
    public static final double P_MOVE_TO_FLOOR = 0.7;

    /** Вероятность создания события установки скидки. */
    public static final double P_SET_DISCOUNT = 0.4;

    /** Вероятность удаления просроченных товаров. */
    public static final double P_REMOVE_EXPIRED = 0.9;

    // ─────────────────────────────────────────────────────────────────────────────
    // Скидки на скоропорт
    // ─────────────────────────────────────────────────────────────────────────────

    /** Если до конца срока годности ≤ этого количества дней — скидка активируется. */
    public static final int PERISHABLE_HORIZON_DAYS = 2;

    /** Размер скидки на скоропорт (%), например 0.30 = 30%. */
    public static final double PERISHABLE_DISCOUNT = 0.30;

    // ─────────────────────────────────────────────────────────────────────────────
    // Покупатели
    // ─────────────────────────────────────────────────────────────────────────────

    /** Минимальное число покупателей в день. */
    public static final int CUSTOMERS_PER_DAY_MIN = 8;

    /** Максимальное число покупателей в день. */
    public static final int CUSTOMERS_PER_DAY_MAX = 16;

    // ─────────────────────────────────────────────────────────────────────────────
    // Ручная генерация дискаунт-событий
    // ─────────────────────────────────────────────────────────────────────────────

    /** Вероятность, что планировщик создаст событие установки временной скидки. */
    public static final double DISCOUNT_EVENT_PROB = 0.3;

    private Config() {
        // Утилитарный класс — создание экземпляров запрещено.
    }
}